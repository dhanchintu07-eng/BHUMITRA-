export function getBenchmarkPriceForCrop(cropId: string, preferredState?: string): APMCRecord | undefined {
  if (preferredState) {
    const stateMatch = APMC_RECORDS.find(
      (r) => r.cropId === cropId && r.state.toLowerCase() === preferredState.toLowerCase()
    );
    if (stateMatch) return stateMatch;
  }
  return APMC_RECORDS.find((r) => r.cropId === cropId);
}
